export function mapLabel(place: Place) {
  return place.id === "ho-guom"
    ? "Hà Nội"
    : place.id === "sai-gon"
      ? "TP. Hồ Chí Minh"
      : place.id === "hoang-sa"
        ? "QĐ. Hoàng Sa"
        : place.id === "truong-sa"
          ? "QĐ. Trường Sa"
          : place.city;
}

export function normalizeSearch(value: string) {
  return value
    .normalize("NFD")
    .replace(/\p{Diacritic}/gu, "")
    .replace(/đ/g, "d")
    .replace(/Đ/g, "D")
    .toLowerCase()
    .trim();
}
export const PROVINCES = [...new Set(PLACES.map((p) => p.province!))].sort(
  (a, b) => a.localeCompare(b, "vi"),
);

export function filterPlaces(
  query: string,
  region: string,
  province = "",
  pool: readonly Place[] = PLACES,
) {
  const term = normalizeSearch(query);
  return pool.filter(
    (place) =>
      (region === "Tất cả" ||
        (region === "Biển đảo"
          ? place.category === "Biển đảo"
          : place.region === region)) &&
      (!province || place.province === province) &&
      normalizeSearch(
        `${place.name} ${place.city} ${place.province ?? ""} ${place.category} ${(place.aliases ?? []).join(" ")} ${place.id.replace(/-/g, " ")}`,
      ).includes(term),
  );
}
